def _int(v, lo, hi, default):
    try:
        return max(lo, min(hi, int(v)))
    except (TypeError, ValueError):
        return default


def _font(f, default):
    f = f if isinstance(f, dict) else {}
    return {"name": str(f.get("name") or default["name"]),
            "size": _int(f.get("size"), 4, 72, default["size"]),
            "weight": f.get("weight") if f.get("weight") in FONT_WEIGHTS else default["weight"],
            "slant": f.get("slant") if f.get("slant") in FONT_SLANTS else default["slant"]}


