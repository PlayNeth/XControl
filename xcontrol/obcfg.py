    out["menu_font"] = _font(out["menu_font"], DEFAULT["menu_font"])
    out["focus_delay"] = _int(out["focus_delay"], 0, 5000, DEFAULT["focus_delay"])
    out["resist_windows"] = _int(out["resist_windows"], 0, 100, DEFAULT["resist_windows"])
    out["resist_edges"] = _int(out["resist_edges"], 0, 100, DEFAULT["resist_edges"])
    out["desktops"] = _int(out["desktops"], 1, 10, DEFAULT["desktops"])
