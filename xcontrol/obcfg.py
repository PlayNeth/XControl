# ---------------------------------------------------------------- XML helpers
def _local(tag):
    return tag.rsplit("}", 1)[-1] if isinstance(tag, str) else tag


def _parse(text):
    """The document with its comments (ElementTree drops them otherwise)."""
    parser = ET.XMLParser(target=ET.TreeBuilder(insert_comments=True))
    return ET.fromstring(text, parser=parser)


def _ns(root):
    m = re.match(r"^\{(.*)\}", root.tag)
    return m.group(1) if m else ""


def _q(ns, tag):
    return f"{{{ns}}}{tag}" if ns else tag


def _child(parent, ns, tag, create=True):
    el = parent.find(_q(ns, tag))
    if el is None and create:
        el = ET.SubElement(parent, _q(ns, tag))
    return el


def _set(parent, ns, tag, value):
    _child(parent, ns, tag).text = str(value)


def _text(parent, ns, path, default=None):
    el = parent.find("/".join(_q(ns, p) for p in path.split("/"))) if parent is not None else None
    return el.text.strip() if el is not None and el.text and el.text.strip() else default


def _yes(v):
    return str(v).strip().lower() in ("yes", "true", "on", "1")


def _yn(b):
    return "yes" if b else "no"


def to_text(elements):
    """Elements as XML text without the namespace (what the page shows and stores)."""
    out = []
    for el in elements:
        el = copy.deepcopy(el)
        el.tail = None
        for e in el.iter():
            if isinstance(e.tag, str):
                e.tag = _local(e.tag)
            # the indentation of a written rc.xml isn't part of a value
            if e.text is not None and not e.text.strip() and len(e):
                e.text = None
            if e is not el and e.tail is not None and not e.tail.strip():
                e.tail = None
        out.append(ET.tostring(el, encoding="unicode", short_empty_elements=True).strip())
    return "".join(out)


def from_text(text, ns):
    """XML text (one or more elements, as to_text gives) back into elements in namespace `ns`.
    Raises ValueError when it isn't well-formed."""
    try:
        wrapper = ET.fromstring(f"<x>{text}</x>")
    except ET.ParseError as e:
        raise ValueError(str(e)) from None
    for e in wrapper.iter():
        if isinstance(e.tag, str) and not e.tag.startswith("{"):
            e.tag = _q(ns, e.tag)
    return list(wrapper)


def check_actions(text):
    """None when `text` is a valid keybind body (actions, or keybinds for a chain), else why not."""
    try:
        els = from_text(text, "")
    except ValueError as e:
        return str(e)
    if not els:
        return "empty"
    bad = [e.tag for e in els if e.tag not in ("action", "keybind")]
    return f"<{bad[0]}> isn't an action" if bad else None


# ---------------------------------------------------------------- keys
_MODS = {"s": "S", "shift": "S", "c": "C", "control": "C", "ctrl": "C", "a": "A", "alt": "A", "mod1": "A",
         "w": "W", "super": "W", "mod4": "W", "m": "M", "meta": "M", "h": "H", "hyper": "H"}


def key_id(keys):
    """A comparable form of an Openbox key: modifiers sorted, case folded. Only the first key of a chain."""
    first = keys.split()[0] if keys.split() else ""
    parts = first.split("-")
    mods = sorted(_MODS.get(p.lower(), p.upper()) for p in parts[:-1])
    return "-".join(mods + [parts[-1].lower()])


def clashes(bindings):
    """{index: [indexes with the same keys]}."""
    seen = {}
    for i, b in enumerate(bindings):
        seen.setdefault(key_id(b["keys"]), []).append(i)
    return {i: [j for j in group if j != i] for group in seen.values() if len(group) > 1 for i in group}


def actions_of(xml_text):
    """[(name, {child tag: text})] of a keybind body, for showing it; [] when it can't be read."""
    try:
        els = from_text(xml_text, "")
    except ValueError:
        return []
    out = []
    for e in els:
        if e.tag == "action":
            out.append((e.get("name", ""), {c.tag: (c.text or "").strip() for c in e if isinstance(c.tag, str)}))
        elif e.tag == "keybind":
            out.append(("chain:" + e.get("key", ""), {}))
    return out


def simple_action(xml_text):
    """(name, argument) when the keybind is one action with at most its main argument, else None."""
    acts = actions_of(xml_text)
    if len(acts) != 1 or acts[0][0].startswith("chain:"):
        return None
    name, args = acts[0]
    main = ACTION_ARGS.get(name)
    if not args:
        return name, ""
    if main and set(args) == {main}:
        return name, args[main]
    return None


ACTION_ARGS = {"Execute": "command", "GoToDesktop": "to", "SendToDesktop": "to", "ShowMenu": "menu"}


def action_xml(name, arg=""):
    """The keybind body for one action and its main argument."""
    el = ET.Element("action", name=name)
    main = ACTION_ARGS.get(name)
    if main:
        ET.SubElement(el, main).text = arg
    return to_text([el])


# ---------------------------------------------------------------- reading rc.xml
def import_config(text, base=None, startup_text=None, managed=None):
    """Settings from an rc.xml (and an autostart file): everything the page covers, with the
    document itself kept as the base the settings are written into. Startup lines for what
    XControl runs now are left out (see i3cfg.MANAGED). Returns (settings, skipped).
    Raises ValueError when the rc.xml isn't readable XML."""
    try:
        root = _parse(text)
    except ET.ParseError as e:
        raise ValueError(str(e)) from None
    ns = _ns(root)
    c = normalize(base or {})
    c["base"] = text
    t = root.find(_q(ns, "theme"))
    if t is not None:
        c["theme"] = _text(t, ns, "name", c["theme"])
        c["title_layout"] = _text(t, ns, "titleLayout", c["title_layout"])
        c["keep_border"] = _yes(_text(t, ns, "keepBorder", "yes"))
        c["animate_iconify"] = _yes(_text(t, ns, "animateIconify", "yes"))
        for f in t.findall(_q(ns, "font")):
            key = {"ActiveWindow": "title_font", "MenuItem": "menu_font"}.get(f.get("place"))
            if key:
                c[key] = {"name": _text(f, ns, "name", c[key]["name"]), "size": _text(f, ns, "size", c[key]["size"]),
                          "weight": (_text(f, ns, "weight", c[key]["weight"]) or "").lower(),
                          "slant": (_text(f, ns, "slant", c[key]["slant"]) or "").lower()}
    f = root.find(_q(ns, "focus"))
    if f is not None:
        c["follow_mouse"] = _yes(_text(f, ns, "followMouse", "no"))
        c["focus_delay"] = _text(f, ns, "focusDelay", c["focus_delay"])
        c["raise_on_focus"] = _yes(_text(f, ns, "raiseOnFocus", "no"))
        c["focus_new"] = _yes(_text(f, ns, "focusNew", "yes"))
    p = root.find(_q(ns, "placement"))
    if p is not None:
        c["placement"] = _text(p, ns, "policy", c["placement"])
        c["center"] = _yes(_text(p, ns, "center", "yes"))
        c["placement_monitor"] = _text(p, ns, "monitor", c["placement_monitor"])
    r = root.find(_q(ns, "resistance"))
    if r is not None:
        c["resist_windows"] = _text(r, ns, "strength", c["resist_windows"])
        c["resist_edges"] = _text(r, ns, "screen_edge_strength", c["resist_edges"])
    d = root.find(_q(ns, "desktops"))
    if d is not None:
        c["desktops"] = _text(d, ns, "number", c["desktops"])
        c["desktop_popup"] = _text(d, ns, "popupTime", c["desktop_popup"])
        names = d.find(_q(ns, "names"))
        c["desktop_names"] = ([(n.text or "").strip() for n in names.findall(_q(ns, "name"))]
                              if names is not None else [])
    k = root.find(_q(ns, "keyboard"))
    c["bindings"] = []
    if k is not None:
        for kb in k.findall(_q(ns, "keybind")):
            if kb.get("key"):
                c["bindings"].append({"keys": kb.get("key"), "xml": to_text([e for e in kb if isinstance(e.tag, str)])})
    c["drag_mod"], c["double_click"] = _mouse_settings(root, ns)
    c["root_menu"] = _root_menu(root, ns, *ROOT_MENUS["root_menu"]) is not None
    c["root_window_list"] = _root_menu(root, ns, *ROOT_MENUS["root_window_list"]) is not None
    c["rules"] = []
    apps = root.find(_q(ns, "applications"))
    if apps is not None:
        for a in apps.findall(_q(ns, "application")):
            c["rules"].append(_rule_from(a, ns))
    skipped = []
    if startup_text is not None:
        c["startup"], skipped = import_autostart(startup_text, managed)
    return normalize(c), skipped


def _contexts(root, ns, name):
    """The <context> elements of <mouse> whose name list includes `name`."""
    mouse = root.find(_q(ns, "mouse"))
    if mouse is None:
        return []
    return [ctx for ctx in mouse.findall(_q(ns, "context")) if name in (ctx.get("name") or "").split()]


def _mouse_settings(root, ns):
    drag, dbl = DEFAULT["drag_mod"], "none"
    for ctx in _contexts(root, ns, "Frame"):
        for mb in ctx.findall(_q(ns, "mousebind")):
            names = [a.get("name") for a in mb.findall(_q(ns, "action"))]
            if mb.get("action") == "Drag" and "Move" in names:
                parts = (mb.get("button") or "").split("-")
                drag = "W" if "W" in parts[:-1] else "A"
    for ctx in _contexts(root, ns, "Titlebar"):
        for mb in ctx.findall(_q(ns, "mousebind")):
            if mb.get("action") == "DoubleClick" and mb.get("button") == "Left":
                acts = mb.findall(_q(ns, "action"))
                dbl = acts[0].get("name") if acts else "none"
    return drag, dbl if dbl in DOUBLE_CLICK else "ToggleMaximize"


ROOT_MENUS = {"root_menu": ("Right", "root-menu"), "root_window_list": ("Middle", "client-list-combined-menu")}


def _root_menu(root, ns, button, menu):
    """(context, mousebind) of the desktop click that shows `menu`, or None (some configs bind it in
    the Desktop context, which a desktop window like pcmanfm's uses)."""
    contexts = _contexts(root, ns, "Root")
    for ctx in contexts + [x for x in _contexts(root, ns, "Desktop") if x not in contexts]:
        for mb in ctx.findall(_q(ns, "mousebind")):
            if mb.get("button") != button:
                continue
            for a in mb.findall(_q(ns, "action")):
                if a.get("name") == "ShowMenu" and _text(a, ns, "menu") == menu:
                    return ctx, mb
    return None


def _rule_from(a, ns):
    match = {k: a.get(k) for k in MATCH_KEYS if a.get(k)}
    settings, raw = {}, []
    for e in a:
        if not isinstance(e.tag, str):
            continue
        tag = _local(e.tag)
        if tag == "position" and all(_local(x.tag) in POSITION_KEYS for x in e if isinstance(x.tag, str)):
            for x in e:
                if isinstance(x.tag, str) and (x.text or "").strip():
                    settings[_local(x.tag)] = x.text.strip()
        elif tag in RULE_KEYS and len(e) == 0 and (e.text or "").strip():
            settings[tag] = e.text.strip()
        else:
            raw.append(e)
    return {"match": match, "settings": settings, "raw": to_text(raw)}


def import_autostart(text, managed=None):
    """Autostart lines as startup entries (the trailing & dropped); the ones XControl takes care of
    are left out. Returns (entries, skipped)."""
    managed = managed_now() if managed is None else set(managed)
    out, skipped = [], []
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        cmd = re.sub(r"\s*&\s*$", "", line)
        if skipped_by(cmd, managed):
            skipped.append(line)
        else:
            out.append({"command": cmd})
    return out, skipped


# ---------------------------------------------------------------- writing rc.xml
def system_rc():
    """Openbox's own rc.xml (what a new user gets), or the built-in fallback."""
    dirs = (os.environ.get("XDG_CONFIG_DIRS") or "/etc/xdg").split(":")
    for d in dirs + [os.path.dirname(os.path.dirname(SYSTEM_RC))]:
        path = os.path.join(d, "openbox", "rc.xml")
        try:
            with open(path, encoding="utf-8", errors="replace") as f:
                text = f.read()
            _parse(text)
            return text
        except (OSError, ET.ParseError):
            continue
    return FALLBACK_RC


def defaults():
    """The page's settings for Openbox's own config."""
    c, _skipped = import_config(system_rc())
    return c


def generate(c):
    """rc.xml text for settings `c` (normalized). Raises ValueError for a binding or rule that
    isn't valid XML."""
    try:
        root = _parse(c["base"] or system_rc())
    except ET.ParseError:
        root = _parse(FALLBACK_RC)
    ns = _ns(root)
    for e in [e for e in root if not isinstance(e.tag, str) and MARK.strip() in (e.text or "")]:
        root.remove(e)
    root.insert(0, ET.Comment(MARK))

    t = _child(root, ns, "theme")
    _set(t, ns, "name", c["theme"])
    _set(t, ns, "titleLayout", c["title_layout"])
    _set(t, ns, "keepBorder", _yn(c["keep_border"]))
    _set(t, ns, "animateIconify", _yn(c["animate_iconify"]))
    for place, key in (("ActiveWindow", "title_font"), ("InactiveWindow", "title_font"),
                       ("MenuHeader", "menu_font"), ("MenuItem", "menu_font")):
        f = next((x for x in t.findall(_q(ns, "font")) if x.get("place") == place), None)
        if f is None:
            f = ET.SubElement(t, _q(ns, "font"), place=place)
        for part in ("name", "size", "weight", "slant"):
            _set(f, ns, part, c[key][part])

    f = _child(root, ns, "focus")
    _set(f, ns, "focusNew", _yn(c["focus_new"]))
    _set(f, ns, "followMouse", _yn(c["follow_mouse"]))
    _set(f, ns, "focusDelay", c["focus_delay"])
    _set(f, ns, "raiseOnFocus", _yn(c["raise_on_focus"]))
    p = _child(root, ns, "placement")
    _set(p, ns, "policy", c["placement"])
    _set(p, ns, "center", _yn(c["center"]))
    _set(p, ns, "monitor", c["placement_monitor"])
    r = _child(root, ns, "resistance")
    _set(r, ns, "strength", c["resist_windows"])
    _set(r, ns, "screen_edge_strength", c["resist_edges"])

    d = _child(root, ns, "desktops")
    _set(d, ns, "number", c["desktops"])
    _set(d, ns, "popupTime", c["desktop_popup"])
    names = _child(d, ns, "names")
    for n in list(names):
        names.remove(n)
    names.text = None
    for n in c["desktop_names"][:c["desktops"]]:
        ET.SubElement(names, _q(ns, "name")).text = n

    k = _child(root, ns, "keyboard")
    for kb in k.findall(_q(ns, "keybind")):
        k.remove(kb)
    for b in c["bindings"]:
        kb = ET.SubElement(k, _q(ns, "keybind"), key=b["keys"])
        kb.extend(from_text(b["xml"], ns))
    _write_mouse(root, ns, c)

    apps = _child(root, ns, "applications")
    for a in list(apps):
        apps.remove(a)
    apps.text = None
    for rule in c["rules"]:
        a = ET.SubElement(apps, _q(ns, "application"), **rule["match"])
        pos = {k: v for k, v in rule["settings"].items() if k in POSITION_KEYS}
        for key in RULE_KEYS:
            if key in rule["settings"] and key not in POSITION_KEYS:
                _set(a, ns, key, rule["settings"][key])
        if pos:
            pe = ET.SubElement(a, _q(ns, "position"), force="yes")
            for key in POSITION_KEYS:
                if key in pos:
                    _set(pe, ns, key, pos[key])
        if rule["raw"]:
            a.extend(from_text(rule["raw"], ns))
    ET.indent(root, space="  ")
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n"


def _write_mouse(root, ns, c):
    mouse = _child(root, ns, "mouse")
    for ctx in _contexts(root, ns, "Frame"):
        for mb in ctx.findall(_q(ns, "mousebind")):
            parts = (mb.get("button") or "").split("-")
            if len(parts) > 1 and any(m in ("A", "W") for m in parts[:-1]):
                mods = [m for m in parts[:-1] if m not in ("A", "W")] + [c["drag_mod"]]
                mb.set("button", "-".join(mods + parts[-1:]))
    for key, (button, menu) in ROOT_MENUS.items():
        found = _root_menu(root, ns, button, menu)
        if found and not c[key]:
            found[0].remove(found[1])
        elif not found and c[key]:
            ctx = next((x for x in _contexts(root, ns, "Root") if x.get("name") == "Root"), None)
            if ctx is None:
                ctx = ET.SubElement(mouse, _q(ns, "context"), name="Root")
            mb = ET.SubElement(ctx, _q(ns, "mousebind"), button=button, action="Press")
            a = ET.SubElement(mb, _q(ns, "action"), name="ShowMenu")
            _set(a, ns, "menu", menu)
    titlebars = _contexts(root, ns, "Titlebar")
    found = False
    for ctx in titlebars:
        for mb in ctx.findall(_q(ns, "mousebind")):
            if mb.get("action") == "DoubleClick" and mb.get("button") == "Left":
                if c["double_click"] == "none":
                    ctx.remove(mb)
                else:
                    for a in list(mb):
                        mb.remove(a)
                    ET.SubElement(mb, _q(ns, "action"), name=c["double_click"])
                found = True
    if not found and c["double_click"] != "none":
        ctx = next((x for x in titlebars if x.get("name") == "Titlebar"), None)
        if ctx is None:
            ctx = ET.SubElement(mouse, _q(ns, "context"), name="Titlebar")
        mb = ET.SubElement(ctx, _q(ns, "mousebind"), button="Left", action="DoubleClick")
        ET.SubElement(mb, _q(ns, "action"), name=c["double_click"])


def autostart_line(cmd):
    """A startup entry as an autostart line: commands go to the background (or the ones after
    them would wait), shell syntax is written as it is."""
    cmd = cmd.strip()
    if cmd.endswith(("&", "\\", ";")) or SHELL_WORDS.match(cmd):
        return cmd
    return cmd + " &"


def generate_autostart(c):
    L = ["#" + MARK.rstrip(), "# Your previous autostart is kept next to this file as autostart.before-xcontrol.",
         "", SESSION_LINE + "   # wallpaper, bar, compositor, lock, input (XControl)"]
    L += [autostart_line(s["command"]) for s in c["startup"]]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- rules as text (the page's table)
def match_text(match):
    return " ".join(f'{k}="{v}"' for k, v in match.items())


def parse_match(text):
    """'class="Steam" title="Friends*"' -> {"class": "Steam", "title": "Friends*"}; a bare word is a class."""
    found = {k: v for k, v in re.findall(r'(\w+)\s*=\s*"([^"]*)"', text) if k in MATCH_KEYS}
    found.update({k: v for k, v in re.findall(r'(\w+)\s*=\s*([^\s"]+)', text) if k in MATCH_KEYS and k not in found})
    if not found and re.match(r"^[\w.*?-]+$", text.strip()):
        found["class"] = text.strip()
    return found


def settings_text(settings):
    return " ".join(f"{k}={v}" for k, v in settings.items())


def parse_settings(text):
    """'desktop=2 decor=no' -> ({"desktop": "2", "decor": "no"}, [unknown keys])."""
    out, unknown = {}, []
    for k, v in re.findall(r'([\w-]+)\s*=\s*("[^"]*"|[^\s,;]+)', text):
        k = k.replace("-", "_")
        if k in RULE_KEYS:
            out[k] = v.strip('"')
        else:
            unknown.append(k)
    return out, unknown


# ---------------------------------------------------------------- on disk
def config_dir():
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")
    return os.path.join(base, "openbox")


def target():
    return os.path.join(config_dir(), "rc.xml")


def autostart_path():
    return os.path.join(config_dir(), "autostart")


def loaded_path():
    """The rc.xml the running Openbox reads (it says so on the root window: LXDE uses
    lxde-rc.xml), else the usual one."""
    if shutil.which("xprop") and os.environ.get("DISPLAY"):
        try:
            out = subprocess.run(["xprop", "-root", "_OB_CONFIG_FILE"], capture_output=True, text=True,
                                 timeout=5).stdout
            m = re.search(r'=\s*"(.*)"', out)
            if m:
                return m.group(1)
        except (OSError, subprocess.SubprocessError):
            pass
    return target()


def is_ours(path=None):
    try:
        with open(path or target(), errors="replace") as f:
            return MARK.strip() in f.read(600)
    except OSError:
        return False


def _keep(path):
    """Move a file that isn't XControl's aside as <path>.before-xcontrol."""
    if os.path.lexists(path) and not is_ours(path):
        dest = path + ".before-xcontrol"
        if os.path.lexists(dest):
            dest += time.strftime("-%Y%m%d-%H%M%S")
        os.rename(path, dest)


def previous():
    """(rc.xml, autostart) Openbox used before XControl's, or the current ones when XControl hasn't
    taken over; None for each that doesn't exist."""
    out = []
    for path in (target(), autostart_path()):
        found = None
        for p in (path + ".before-xcontrol", path):
            if os.path.exists(p) and not is_ours(p):
                found = p
                break
        out.append(found)
    return tuple(out)


def _write_file(path, text):
    """Write next to the file first, so a full disk leaves the user's file where it was."""
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    try:
        with open(path + ".tmp", "w", encoding="utf-8") as f:
            f.write(text)
        _keep(path)
        os.replace(path + ".tmp", path)
    except OSError:
        try:
            os.remove(path + ".tmp")
        except OSError:
            pass
        raise
    return True


def write(c):
    """Write rc.xml and autostart, then reconfigure Openbox. Returns (ok, errors)."""
    try:
        text = generate(c)
        _parse(text)   # (well-formed, or nothing is written)
    except (ValueError, ET.ParseError) as e:
        return False, [str(e)]
    changed = _write_file(target(), text)
    _write_file(autostart_path(), generate_autostart(c))
    if changed:
        reload()
    return True, []


def refresh():
    """Write XControl's Openbox files again from the saved settings (after a backup is restored)."""
    c = load()
    if c["enabled"] and is_ours():
        return write(c)
    return True, []


def restore():
    """Put the previous files back (XControl's are kept as <name>.xcontrol)."""
    found = False
    for path in (target(), autostart_path()):
        if os.path.lexists(path + ".before-xcontrol"):
            if is_ours(path):
                os.replace(path, path + ".xcontrol")
            if not os.path.lexists(path):
                os.rename(path + ".before-xcontrol", path)
                found = True
        elif is_ours(path):   # there was none before: Openbox's own defaults again
            os.replace(path, path + ".xcontrol")
            found = True
    if found:
        reload()
    return found


def can_restore():
    return any(os.path.lexists(p + ".before-xcontrol") for p in (target(), autostart_path()))


def reload():
    if shutil.which("openbox") and os.environ.get("DISPLAY"):
        try:   # Openbox not running: it just fails
            subprocess.run(["openbox", "--reconfigure"], capture_output=True, timeout=10)
        except (OSError, subprocess.SubprocessError):
            pass


_version = {}


def version():
    """Openbox's (major, minor, patch), or None when it isn't installed."""
    exe = shutil.which("openbox")
    if not exe:
        return None
    try:
        key = (exe, os.stat(exe).st_mtime)
    except OSError:
        return None
    if key not in _version:
        try:
            out = subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=5).stdout
        except (OSError, subprocess.SubprocessError):
            return None
        m = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", out)
        _version.clear()
        _version[key] = tuple(int(x or 0) for x in m.groups()) if m else None
    return _version[key]


def themes():
    """Installed Openbox themes (folders with openbox-3/themerc), sorted."""
    home = os.path.expanduser("~")
    data = os.environ.get("XDG_DATA_HOME") or os.path.join(home, ".local", "share")
    dirs = [os.path.join(home, ".themes"), os.path.join(data, "themes")]
    dirs += [os.path.join(d, "themes") for d in (os.environ.get("XDG_DATA_DIRS") or "/usr/local/share:/usr/share")
             .split(":") if d]
    found = set()
    for d in dirs:
        try:
            names = os.listdir(d)
        except OSError:
            continue
        found.update(n for n in names if os.path.isfile(os.path.join(d, n, "openbox-3", "themerc")))
    return sorted(found, key=str.lower)
