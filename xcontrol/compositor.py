"""XControl's picom: settings -> ~/.config/xcontrol/picom.conf.

Generated from scratch on every change (your own picom.conf isn't used while XControl
runs picom). Only options that work from picom 9 up to 12 are written, with exclusions
that keep docks (the bar), the desktop, drag-and-drop icons and i3's own frames clean.
"""
import os
import re
import shutil
import subprocess

from .paths import config_dir

BACKENDS = ["glx", "xrender", "egl"]
BLUR = {"off": 0, "light": 3, "medium": 5, "strong": 8}
DEFAULT = {
    "enabled": False, "backend": "glx", "vsync": True, "unredirect": True,
    "shadows": True, "shadow_radius": 12, "shadow_opacity": 50,
    "fading": True, "fade_speed": 6,           # percent per 5 ms step: 6 = about 80 ms
    "active_opacity": 100, "inactive_opacity": 100, "corner_radius": 0, "blur": "off",
}


def normalize(p):
    out = dict(DEFAULT)
    if isinstance(p, dict):
        out.update({k: v for k, v in p.items() if k in DEFAULT})
    if out["backend"] not in BACKENDS:
        out["backend"] = "glx"
    if out["blur"] not in BLUR:
        out["blur"] = "off"
    for k, lo, hi in (("shadow_radius", 0, 40), ("shadow_opacity", 0, 100), ("fade_speed", 1, 30),
                      ("active_opacity", 30, 100), ("inactive_opacity", 30, 100), ("corner_radius", 0, 30)):
        out[k] = max(lo, min(hi, int(out[k])))
    return out


def config_path():
    return os.path.join(config_dir(), "picom.conf")


def version():
    """(major, minor) of the installed picom ('v12.5', 'v10.2-xx' ...), or None."""
    if not shutil.which("picom"):
        return None
    try:
        out = subprocess.run(["picom", "--version"], capture_output=True, text=True, timeout=5).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    m = re.search(r"v?(\d+)(?:\.(\d+))?", out)
    return (int(m.group(1)), int(m.group(2) or 0)) if m else None


def _list(items):
    return "[\n" + ",\n".join(f'  "{i}"' for i in items) + "\n];"


def generate(p, ver=None):
    ver = ver if ver is not None else version()
    backend = p["backend"]
    if backend == "egl" and ver and ver < (10, 0):
        backend = "glx"   # egl came with picom 10
    blur = BLUR[p["blur"]] if backend != "xrender" else 0   # blur needs a GL backend to be usable
    no_effects = ["window_type = 'dock'", "window_type = 'desktop'", "window_type = 'dnd'",
                  "class_g = 'i3-frame'", "_GTK_FRAME_EXTENTS@:c"]
    radius = p["shadow_radius"]
    lines = [
        "# Generated by XControl (Bar & Compositor page). It's rewritten on every change;",
        "# edits here are lost. Your own picom.conf isn't used while XControl runs picom.",
        "",
        f'backend = "{backend}";',
        f"vsync = {'true' if p['vsync'] else 'false'};",
        # full-screen games skip the compositor: lower latency, and FreeSync needs it
        f"unredir-if-possible = {'true' if p['unredirect'] else 'false'};",
        "use-damage = true;",
        "detect-client-opacity = true;",
        "detect-transient = true;",
        "mark-wmwin-focused = true;",
        "mark-ovredir-focused = true;",
        "",
        f"shadow = {'true' if p['shadows'] and radius else 'false'};",
        f"shadow-radius = {radius};",
        f"shadow-opacity = {p['shadow_opacity'] / 100:.2f};",
        f"shadow-offset-x = {-radius};",
        f"shadow-offset-y = {-radius};",
        "shadow-exclude = " + _list(no_effects + ["window_type = 'menu'", "window_type = 'dropdown_menu'",
                                                   "window_type = 'popup_menu'", "window_type = 'tooltip'",
                                                   "window_type = 'notification' && class_g = 'Polybar'"]),
        "",
        f"fading = {'true' if p['fading'] else 'false'};",
        f"fade-in-step = {p['fade_speed'] / 100:.2f};",
        f"fade-out-step = {p['fade_speed'] / 100:.2f};",
        "fade-delta = 5;",
        "no-fading-openclose = false;",
        "",
        f"active-opacity = {p['active_opacity'] / 100:.2f};",
        f"inactive-opacity = {p['inactive_opacity'] / 100:.2f};",
        "frame-opacity = 1.0;",
        "inactive-opacity-override = false;",
        "focus-exclude = " + _list(["window_type = 'dock'", "window_type = 'desktop'", "class_g = 'i3lock'",
                                    "fullscreen"]),
        "",
        f"corner-radius = {p['corner_radius']};",
        "rounded-corners-exclude = " + _list(["window_type = 'dock'", "window_type = 'desktop'",
                                              "window_type = 'tooltip'", "window_type = 'menu'",
                                              "window_type = 'dropdown_menu'", "window_type = 'popup_menu'"]),
        "",
    ]
    if blur:
        lines += [
            'blur-method = "dual_kawase";',
            f"blur-strength = {blur};",
            "blur-background = true;",
            "blur-background-frame = false;",
            "blur-background-fixed = false;",
            "blur-background-exclude = " + _list(no_effects + ["class_g = 'slop'", "class_g = 'i3lock'"]),
            "",
        ]
    lines += [
        "wintypes: {",
        "  tooltip = { fade = true; shadow = false; opacity = 1.0; focus = true; };",
        "  dock = { shadow = false; clip-shadow-above = true; };",
        "  dnd = { shadow = false; };",
        "  popup_menu = { opacity = 1.0; };",
        "  dropdown_menu = { opacity = 1.0; };",
        "};",
        "",
    ]
    return "\n".join(lines)


def write(p, **kw):
    text = generate(p, **kw)
    path = config_path()
    try:
        with open(path) as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path + ".tmp", "w") as f:
        f.write(text)
    os.replace(path + ".tmp", path)
    return True


def command():
    return ["picom", "--config", config_path()]
